let current = "cs";

export const lang = () => current;

export function setLang(code) {
  current = code === "en" ? "en" : "cs";
  document.documentElement.lang = current;
}

// Text for key with {name} placeholders filled from vars.
export function t(key, vars = {}) {
  const s = STRINGS[current][key] ?? STRINGS.en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => (k in vars ? String(vars[k]) : `{${k}}`));
}

// Fill the static texts below root.
export function applyStatic(root) {
  root.querySelectorAll("[data-i18n]").forEach((el) => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll("[data-i18n-title]").forEach((el) => { el.title = t(el.dataset.i18nTitle); });
}

// Number with one decimal in the current language's style; sign adds "+" or a minus sign.
export function num(v, digits = 1, sign = false) {
  const s = new Intl.NumberFormat(current === "cs" ? "cs-CZ" : "en-GB", { minimumFractionDigits: digits, maximumFractionDigits: digits }).format(Math.abs(v));
  return (v < 0 ? "−" : sign ? "+" : "") + s;
}

// Compass direction for a bearing in degrees.
export const dir = (deg) => t("dirs").split(",")[Math.round((((deg % 360) + 360) % 360) / 45) % 8];